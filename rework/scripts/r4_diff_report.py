#!/usr/bin/env python3
"""
r4_diff_report.py

Builds rework/outputs/diffs/impact_memo.md — the before/after summary of
what the rework changes in the D5 deliverable.

Two kinds of numbers go in here, and the memo says which is which:
  1. SELF-VERIFIED — recomputed directly in this script from structured
     columns in rework/data/D5_rework_record_summary.csv and our own
     before/after step15_human.csv / step15b_summary.json. These are
     independent of Forrest's prose and will catch a drift if his report
     and data ever disagree.
  2. CITED FROM THE REWORK REPORT — qualitative category breakdowns (e.g.
     "why" for the 36 exclusions, the systematic field-level bias table)
     that come from the lead reviewer's own categorisation of free-text
     rationale, not from a machine-countable column. Re-deriving these by
     regex over messy legacy free text would be less reliable than citing
     the already-audited figures (97.8% evidence-quote verification,
     blinded A/B audit preferring the rework 89.5% of the time). Cited
     verbatim from rework/data/D5_Coding_Rework_Executive_Summary.md.

Run (after r1_build_database.py and r3_gen_prisma_rework.py):
  conda run -n ilri01 python rework/scripts/r4_diff_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

REWORK_ROOT = Path(__file__).parent.parent
REPO_ROOT = REWORK_ROOT.parent
DATA = REWORK_ROOT / "data"
OUT_DIFFS = REWORK_ROOT / "outputs" / "diffs"

OLD_HUMAN_CSV = REPO_ROOT / "scripts" / "outputs" / "step15" / "step15_human.csv"
OLD_SUMMARY = REPO_ROOT / "scripts" / "outputs" / "step15" / "step15b_summary.json"
NEW_HUMAN_CSV = REWORK_ROOT / "outputs" / "step15" / "step15_human.csv"
NEW_SUMMARY = REWORK_ROOT / "outputs" / "step15" / "step15b_summary.json"


def main() -> None:
    old_summary = json.loads(OLD_SUMMARY.read_text())
    new_summary = json.loads(NEW_SUMMARY.read_text())
    old_human = pd.read_csv(OLD_HUMAN_CSV, dtype=str)
    new_human = pd.read_csv(NEW_HUMAN_CSV, dtype=str)

    rs = pd.read_csv(DATA / "D5_rework_record_summary.csv", dtype=str)
    rs["n_fields_substantive_disagreement"] = pd.to_numeric(
        rs["n_fields_substantive_disagreement"], errors="coerce"
    )

    # Eligibility counts come from the 2026-10-26 re-pull (D5_rework_database.csv,
    # confirmed_include) — rs (record_summary.csv) wasn't re-pulled since it's
    # unaffected (field-coding quality, not eligibility); only use it below for
    # sections 2-4.
    db = pd.read_csv(DATA / "D5_rework_database.csv", dtype=str)
    n_coded = db["rework_status"].eq("coded").sum()
    n_confirmed_yes = db["confirmed_include"].eq("yes").sum()
    n_confirmed_no = db["confirmed_include"].eq("no").sum()
    borderline_all = db[db["borderline_flag"].astype(str).str.lower() == "true"]
    borderline_excl = borderline_all[borderline_all["confirmed_include"] == "no"]
    borderline_incl = borderline_all[borderline_all["confirmed_include"] == "yes"]
    flips = db[
        db["confirmed_include"].str.lower().isin(["yes", "no"])
        & db["final_include"].str.lower().isin(["yes", "no"])
        & (db["confirmed_include"].str.lower() != db["final_include"].str.lower())
    ]

    quality = rs["overall_prior_quality"].value_counts(dropna=True)
    avg_disagree = rs["n_fields_substantive_disagreement"].mean()
    med_disagree = rs["n_fields_substantive_disagreement"].median()

    bib_issue_mask = (
        rs["doi_ok"].eq("FALSE") | rs["title_ok"].eq("FALSE") | rs["year_ok"].eq("FALSE")
    )
    n_bib_issues = bib_issue_mask.sum()

    lines = []
    a = lines.append

    a("# D5 Rework — Impact Memo (PRELIM)")
    a("")
    a("Generated by `rework/scripts/r4_diff_report.py` from "
      "`rework/data/D5_rework_*.csv` (database + borderline assessment re-pulled "
      "from Drive 2026-10-26; other rework data files still the 2026-10-21 pull — "
      "see module docstring) and the live pipeline's `scripts/outputs/step15/`. "
      "See `rework/README.md` for full provenance.")
    a("")
    a(f"**Status: PRELIMINARY, borderline-adjudicated.** Eligibility now uses "
      f"`confirmed_include` as ground truth: the AI rework's own recommendation "
      f"(115/151 included, 36 exclusions), hand-checked against all 27 borderline "
      f"cases by Forrest and Caro on 2026-10-26 ({len(flips)} overrides of the "
      f"AI's borderline call — see §1), giving **108/151 confirmed included**. "
      f"Supersedes the 2026-10-21 prelim pass, which accepted the AI's own "
      f"final_include as-is pending this human check. Still leaves the 4 "
      f"out-of-window records and the FT-021 book-split question unresolved "
      f"(footnoted only) — not a final position until co-authors sign off on "
      f"those and the metadata corrections.")
    a("")

    a("## 1. Eligibility / PRISMA — self-verified")
    a("")
    a("| | Before (RA coding) | After (rework, borderline-adjudicated) | Change |")
    a("|---|---:|---:|---:|")
    a(f"| Full texts sought & coded | {old_summary['total_coder_rows']} | "
      f"{new_summary['total_coder_rows']} | — |")
    a(f"| Excluded at full-text stage | {old_summary['excluded_before_filter']} | "
      f"{new_summary['excluded_before_filter']} | "
      f"+{new_summary['excluded_before_filter'] - old_summary['excluded_before_filter']} |")
    a(f"| **Included in systematic map** | **{old_summary['final_human_records']}** | "
      f"**{new_summary['final_human_records']}** | "
      f"{new_summary['final_human_records'] - old_summary['final_human_records']} "
      f"({round(100 * (new_summary['final_human_records'] - old_summary['final_human_records']) / old_summary['final_human_records'], 1)}%) |")
    a("")
    a(f"Of the {n_coded} records the rework could assess for eligibility "
      f"(FT-005 has no full text and is excluded from this count): "
      f"**{n_confirmed_yes} confirmed included** and **{n_confirmed_no} confirmed excluded**.")
    a("")
    a(f"Borderline-case breakdown (27 cases, human-checked 2026-10-26): "
      f"**{len(borderline_incl)} confirmed included**, **{len(borderline_excl)} confirmed "
      f"excluded**. Of those, {len(flips)} flipped from the AI rework's own `final_include` "
      f"call (8 include→exclude, 1 exclude→include — see "
      f"`rework/data/D5_rework_borderline_assessment.csv`).")
    a("")
    a("New PRISMA diagram: `rework/outputs/diffs/prisma_flow_d5_rework.png` "
      "— compare against `deliverables/prisma_flow_d5.png` (original).")
    a("")

    a("## 2. Prior-coding quality — self-verified")
    a("")
    a("Lead-reviewer rating of the RA coding, against `CODEBOOK_FT`, before any rework value "
      "was decided (from `D5_rework_record_summary.csv::overall_prior_quality`):")
    a("")
    a("| Rating | n |")
    a("|---|---:|")
    for rating in ["good", "acceptable", "poor"]:
        a(f"| {rating} | {int(quality.get(rating, 0))} |")
    a("")
    a(f"Average substantive field disagreement per record: **{avg_disagree:.2f} / 16** "
      f"(median {med_disagree:.0f}).")
    a("")
    a(f"Bibliographic issues (DOI/title/year flagged `FALSE`): **{int(n_bib_issues)} records**.")
    a("")

    a("## 3. Why records were excluded — cited from the rework report")
    a("")
    a("(Categorisation is the lead reviewer's own grouping of free-text rationale in "
      "`D5_rework_record_summary.csv::exclusion_reason` — not machine-countable, see "
      "module docstring. Quoted from "
      "`rework/data/D5_Coding_Rework_Executive_Summary.md`.)")
    a("")
    a("- Climate only background, not the driver of the research question — 16 records")
    a("- No adaptation process or outcome measured — 9 records")
    a("- On-station agronomic trials, no farmer/adoption analysis — 5 records")
    a("- Non-empirical reviews or workshop papers — 3 records")
    a("- Non-smallholder populations — 3 records")
    a("")

    a("## 4. Systematic field-level coding bias — cited from the rework report")
    a("")
    a("(Before -> after value counts across all 151 re-coded records, independent of the "
      "eligibility question above. Cited, not recomputed here — see module docstring for why.)")
    a("")
    a("| Field | Value | Before | After |")
    a("|---|---|---:|---:|")
    a("| marginalized_subpopulations | youth | 51 | 8 |")
    a("| marginalized_subpopulations | none_reported | 57 | 90 |")
    a("| geographic_scale | local | 40 | 15 |")
    a("| geographic_scale | sub-national | ~90 | 118 |")
    a("| geographic_scale | regional | 4 | 0 |")
    a("| geographic_scale | multi-country | 6 | 12 |")
    a("| producer_type | mixed | 51 | 20 |")
    a("| methodological_approach | participatory | 38 | 13 |")
    a("| methodological_approach | experimental | 11 | 24 |")
    a("| process_outcome_domains | decision_making_planning | 75 | 33 |")
    a("| process_outcome_domains | risk_reduction | 32 | 13 |")
    a("| process_outcome_domains | access_information_services | 36 | 75 |")
    a("| cost_data_reported | yes | 32 | 23 |")
    a("")
    a("Free text: 35% of `strengths_and_limitations` and 36% of `lessons_learned` entries "
      "disagree outright between prior and rework coding.")
    a("")

    a("## 5. What this means for the figures")
    a("")
    a(f"Every EGM/geographic/methodology/equity/temporal figure under "
      f"`rework/outputs/step16/interactive/human/` is now built from the {n_confirmed_yes}-record "
      f"borderline-adjudicated rework database instead of the 151-record RA database. Given the "
      f"bias directions "
      "above, expect the new Evidence Gap Map to show noticeably less `youth`/`decision_"
      "making_planning`/`risk_reduction` coverage and more `none_reported`/`access_"
      "information_services`/`experimental` than the original — this is a correction of "
      "over- and under-coding, not new evidence. Compare figure-by-figure against "
      "`scripts/outputs/step16/interactive/human/` (original) for the full picture.")
    a("")

    a("## 6. Open decisions before this stops being PRELIM")
    a("")
    a("Borderline eligibility is now resolved (§1). See "
      "`rework/data/D5_Coding_Rework_Executive_Summary.md` ('Decisions needed from "
      "co-authors') for full detail on what's still outstanding:")
    a("- Decide on 4 included records published in 2026 (outside the 2005–2025 window): "
      "FT-093, FT-096, FT-111, FT-137.")
    a("- Decide whether to split FT-021 (edited book) into chapter-level records.")
    a("- Adopt the corrected DOIs/titles/years (13 records).")
    a("- Decide what to do with FT-005 (no full text).")
    a("")
    a("Next (per `work/handover/ilri.md`, Forrest's 2026-10-26 ask): filter the confirmed-"
      "include records on `process_outcome_domains`/`indicators_measured` for yield/income-"
      "based outcome methods — the subset to hand off to D6.")
    a("")

    OUT_DIFFS.mkdir(parents=True, exist_ok=True)
    out_path = OUT_DIFFS / "impact_memo.md"
    out_path.write_text("\n".join(lines))
    print(f"[r4] Wrote -> {out_path}")


if __name__ == "__main__":
    main()
